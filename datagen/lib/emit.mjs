// emit.mjs - turn (shapes x groups x materials) into pack files. Pure functions: nothing touches the disk here.
import { FACES } from "./materials.mjs";
import { cmpVersion, sortKeys, titleCase, toJson } from "./util.mjs";
import { stringifyCompact } from "./geometry.mjs";

const clone = (o) => JSON.parse(JSON.stringify(o));

export const variantId = (cfg, shape, group) => `${shape.id}${cfg.blocks.separator}${group.id}`;

/** Material instances for one material under one render method. */
function instancesFor(material, render, tintAllowed = true) {
  const mk = (face) => {
    const i = { texture: material.faces[face], render_method: render };
    if (material.isotropic?.[face]) i.isotropic = true;
    const t = tintAllowed ? material.tint?.[face] : null;
    if (t && t !== "none") i.tint_method = t;
    return i;
  };
  const per = Object.fromEntries(FACES.map((f) => [f, mk(f)]));
  const same = FACES.every((f) => JSON.stringify(per[f]) === JSON.stringify(per.north));
  if (same) return { "*": per.north };
  return { "*": per.north, ...per };
}

export function renderMethodFor(shape, group) {
  return group.render === "opaque" ? shape.defaultRender : group.render;
}

export function buildVariantBlock({ cfg, shape, group, materialsByName }) {
  const json = clone(shape.json);
  // Bedrock requires format_version >= 1.21.70 to use isotropic in block material_instances
  if (cmpVersion(json.format_version || "1.21.60", "1.21.70") < 0) {
    json.format_version = "1.21.70";
  }
  const block = json["minecraft:block"];
  const desc = block.description;
  const state = cfg.blocks.stateName;
  const render = renderMethodFor(shape, group);

  desc.identifier = variantId(cfg, shape, group);
  delete desc.menu_category; // variants are reached by texturing a base block, not from the creative menu
  // Bedrock requires custom block state enums to have at least 2 values
  const stateValues = group.values.length === 1 ? [...group.values, "_unused"] : [...group.values];
  desc.states = { ...(desc.states ?? {}), [state]: stateValues };

  block.components = block.components ?? {};
  block.components["minecraft:material_instances"] = { "*": { texture: cfg.blocks.baseTexture, render_method: render } };
  block.components["minecraft:loot"] = shape.lootPath;

  const perms = block.permutations ?? [];
  const retired = new Set(group.retired);
  for (const value of group.values) {
    const components = {};
    const m = materialsByName.get(value);
    if (retired.has(value) || !m) {
      components["minecraft:material_instances"] = { "*": { texture: cfg.blocks.baseTexture, render_method: render } };
    } else {
      components["minecraft:material_instances"] = instancesFor(m, render);
      if (m.light > 0) components["minecraft:light_emission"] = m.light;
    }
    perms.push({ condition: `q.block_state('${state}') == '${value}'`, components });
  }
  block.permutations = perms;
  return json;
}

function placeSound(vanilla, soundKey) {
  const ev = vanilla.blockSounds[soundKey]?.events ?? {};
  const pick = (e) => (e && e.sound ? { sound: e.sound, volume: Array.isArray(e.volume) ? e.volume[0] : e.volume ?? 1, pitch: Array.isArray(e.pitch) ? e.pitch : [e.pitch ?? 1, e.pitch ?? 1] } : null);
  return { place: pick(ev.place), break: pick(ev.break), trapdoorOpen: pick(ev["trapdoor.open"]), trapdoorClose: pick(ev["trapdoor.close"]) };
}

export function buildRegistryModule({ cfg, vanilla, shapes, groups, materials, fingerprint }) {
  const texturable = shapes.filter((s) => s.texturable);
  const soundKeys = [...new Set([cfg.blocks.baseSound, ...groups.map((g) => g.sound)])].sort();
  const data = {
    meta: {
      generator: 1,
      engineVersion: vanilla.engineVersion,
      collisionDataVersion: vanilla.mcdVersion,
      fingerprint,
      stateName: cfg.blocks.stateName,
      separator: cfg.blocks.separator,
      baseSound: cfg.blocks.baseSound,
    },
    shapes: Object.fromEntries(shapes.map((s) => [s.id, {
      texturable: s.texturable,
      rotate: s.transform.rotate,
      position: s.transform.position,
      connections: s.connections,
    }])),
    groups: Object.fromEntries(groups.map((g) => [g.id, { sound: g.sound, render: g.render, values: g.values, retired: g.retired }])),
    // item id (without "minecraft:") -> [group id, state value]
    materials: Object.fromEntries(materials.map((m) => {
      const g = groups.find((x) => x.values.includes(m.name) && !x.retired.includes(m.name));
      return [m.name, [g.id, m.name]];
    })),
    sounds: Object.fromEntries(soundKeys.map((k) => [k, placeSound(vanilla, k)])),
    knownVanillaBlocks: vanilla.blockNames,
  };
  const { knownVanillaBlocks: _omit, ...rest } = data;
  const body = stringifyCompact(sortKeys(rest));
  const known = JSON.stringify(vanilla.blockNames);
  return [
    "// AUTO-GENERATED by datagen/run.mjs - DO NOT EDIT. Re-run `node datagen/run.mjs` to refresh.",
    `// Minecraft data snapshot: ${vanilla.engineVersion} (collision data ${vanilla.mcdVersion}), ${materials.length} materials, ${groups.length} groups, ${texturable.length} texturable shapes.`,
    `export const REGISTRY = ${body};`,
    "",
    "/** Every vanilla block id (without namespace) that existed when this file was generated. */",
    `export const KNOWN_VANILLA_BLOCKS = ${known};`,
    "",
  ].join("\n");
}

export function buildBlocksJson({ cfg, shapes, groups, existing }) {
  const out = {};
  const ns = `${cfg.namespace}:`;
  // keep entries that are not ours; drop our own (current + legacy short-name keys) so nothing is duplicated
  const ownShort = new Set(shapes.map((s) => s.name));
  for (const [k, v] of Object.entries(existing ?? {})) {
    if (k === "format_version") continue;
    if (k.startsWith(ns) || ownShort.has(k) || k.startsWith("copycat_")) continue;
    out[k] = v;
  }
  const ours = {};
  for (const s of shapes) {
    ours[s.id] = { sound: cfg.blocks.baseSound };
    if (s.texturable) for (const g of groups) ours[variantId(cfg, s, g)] = { sound: g.sound };
  }
  return toJson({ format_version: existing?.format_version ?? "1.21.0", ...sortKeys(out), ...sortKeys(ours) });
}

export function buildLootTable(shape) {
  return toJson({ pools: [{ rolls: 1, entries: [{ type: "item", name: shape.id, weight: 1, functions: [{ function: "set_count", count: 1 }] }] }] });
}

const BEGIN = "## BEGIN GENERATED (datagen) - do not edit between these markers";
const END = "## END GENERATED (datagen)";

/** Replace (or append) the generated region of en_US.lang. Hand-written lines outside the markers are untouched. */
export function mergeLang({ cfg, shapes, groups, existing, baseNames }) {
  const lines = [];
  for (const s of shapes) {
    if (!s.texturable) continue;
    const name = baseNames.get(s.id) ?? `Copycat ${titleCase(s.name.replace(/^copycat_/, ""))}`;
    for (const g of groups) lines.push(`tile.${variantId(cfg, s, g)}.name=${name}`);
  }
  const region = [BEGIN, ...lines, END].join("\n");
  const text = existing ?? "";
  const re = new RegExp(`\\r?\\n?${BEGIN.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}[\\s\\S]*?${END.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}`);
  let body = re.test(text) ? text.replace(re, "") : text;
  body = body.replace(/\s+$/, "");
  return body + "\n\n" + region + "\n";
}
